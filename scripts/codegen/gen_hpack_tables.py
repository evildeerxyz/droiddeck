#!/usr/bin/env python3
"""Generates HPACKTables.swift from the text of RFC 7541 (Appendix A and B).

Usage: python3 -I gen_hpack_tables.py rfc7541.txt > HPACKTables.swift
"""
import re
import sys

text = open(sys.argv[1]).read().split("\n")

start = next(i for i, l in enumerate(text) if l.startswith("Appendix B.  Huffman Code"))
codes = {}
for line in text[start:start + 400]:
    m = re.match(r"\s*(?:'.'|EOS)?\s*\(\s*(\d+)\)\s+([|01]+)\s+([0-9a-f]+)\s+\[\s*(\d+)\]", line)
    if m:
        codes[int(m.group(1))] = (int(m.group(3), 16), int(m.group(4)))
assert len(codes) == 257, len(codes)

astart = next(i for i, l in enumerate(text) if l.startswith("Appendix A.  Static Table Definition"))
static = {}
for line in text[astart:astart + 120]:
    m = re.match(r"\s*\|\s*(\d+)\s*\|\s*(\S+)\s*\|\s*(.*?)\s*\|\s*$", line)
    if m:
        static[int(m.group(1))] = (m.group(2), m.group(3))
assert len(static) == 61, len(static)

print("// Generated by scripts/codegen/gen_hpack_tables.py from RFC 7541. Do not edit.")
print()
print("enum HPACKTables {")
print("    /// RFC 7541 Appendix A. Index 1 is the first element.")
print("    static let staticTable: [(name: String, value: String)] = [")
for i in range(1, 62):
    n, v = static[i]
    print(f'        ("{n}", "{v}"),')
print("    ]")
print()
print("    /// RFC 7541 Appendix B. (code aligned to LSB, bit length), indexed by symbol; 256 is EOS.")
print("    static let huffmanCodes: [(code: UInt32, length: UInt8)] = [")
for i in range(257):
    c, l = codes[i]
    print(f"        (0x{c:x}, {l}),")
print("    ]")
print("}")
